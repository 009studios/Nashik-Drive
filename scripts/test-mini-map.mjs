import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const read=name=>fs.readFileSync(new URL(name,root),'utf8');
const env={};env.window=env;env.globalThis=env;env.devicePixelRatio=2;
vm.runInNewContext(read('shapes.js'),env);
vm.runInNewContext(read('mini-map.js'),env);
const world=JSON.parse(read('world.json'));
assert.equal(world.roadNetwork.roads.length,285);
assert.equal(world.blocks.length,561);
const index=env.NashikMiniMap.indexFeatures(world.roadNetwork.roads,world.blocks,env.NashikShapes);
const [u,v]=world.mapEdits.spawn;
const nearby=env.NashikMiniMap.queryNearby(index,u,v,80/world.mapScale);
assert.ok(nearby.roads.length>0,'player should have roads nearby');
assert.ok(nearby.roads.length<285,'local viewport should not include every city road');
assert.ok(nearby.buildings.length<561,'local viewport should not include every building');
const operations=[];
const ctx={
 setTransform(){},fillRect(){},save(){},beginPath(){},rect(){},clip(){},translate(){},scale(){},restore(){},moveTo(x,y){operations.push(['move',x,y]);},lineTo(x,y){operations.push(['line',x,y]);},stroke(){},fill(){},closePath(){},fillText(){},drawImage(){}
};
const canvas={width:0,height:0,clientWidth:158,getContext:()=>ctx};
const mini=env.NashikMiniMap.create(canvas,{roads:world.roadNetwork.roads,blocks:world.blocks,shapes:env.NashikShapes,metresPerPixel:world.mapScale,visibleMetres:160});
mini.draw(u,v);
const [roundX,roundY]=mini.fromWorld((u-1175/2)*world.mapScale,(v-1280/2)*world.mapScale);
assert.ok(Math.abs(roundX-u)<1e-8 && Math.abs(roundY-v)<1e-8,'world->minimap coordinates must match WebGL coordinates');
operations.length=0;
mini.drawWorld((u-1175/2)*world.mapScale,(v-1280/2)*world.mapScale);
const worldOperations=JSON.stringify(operations);
operations.length=0;
mini.draw(u,v);
assert.equal(worldOperations,JSON.stringify(operations),'world and map coordinates must draw identical streets');
assert.equal(canvas.width,316);
assert.ok(operations.length>20,'nearby roads and buildings must actually be drawn');
const before=JSON.stringify(operations);
operations.length=0;mini.draw(u+50,v-35);
assert.notEqual(before,JSON.stringify(operations),'the map should move as the player drives');
const html=read('index.html');
assert.ok(html.includes('id="minimap-canvas"'));
assert.ok(html.includes('id="map-overlay" class="hidden"'));
assert.ok(!html.includes('mini-map-inner"><img src="map_preview.png"'));
const game=read('game.js');
assert.ok(game.includes('marker.style.transform=`translate(-50%, -50%) rotate('),'heading indicator must rotate without moving its centre');
assert.ok(!game.includes('marker.style.rotate='),'separate CSS rotate causes offset risks');
console.log(`PASS: ${nearby.roads.length} of 285 roads and ${nearby.buildings.length} of 561 buildings are in the player's local area; local map moves with player; full map remains hidden by default.`);
