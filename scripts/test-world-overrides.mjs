import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const read=f=>fs.readFileSync(new URL('../'+f,import.meta.url),'utf8');
const env={};env.window=env;env.globalThis=env;
vm.runInNewContext(read('world-overrides.js'),env);
const A=env.NashikWorldOverrides;
const source=JSON.parse(read('world.json'));
const count=source.blocks.length,roadCount=source.roadNetwork.roads.length;
const patch=A.empty(source),id=A.blockId(source.blocks[0],0),roadId=source.roadNetwork.roads[0].id;
assert.ok(id.startsWith('osm:'));
patch.buildings[id]={h:18.2,floors:6,kind:'commercial',facade:{windows:true,roof:'flat'}};
patch.roads[String(roadId)]={widthM:12};
patch.assetsAdded=[{id:'studio:test_1234',type:'median',x:660,y:620,w:3,d:.4,h:.7,rot:0}];
const original=JSON.stringify(source),edited=A.apply(JSON.parse(original),patch);
assert.equal(edited.blocks.length,count);assert.equal(edited.roadNetwork.roads.length,roadCount);
assert.equal(edited.blocks[0][4],18.2);assert.equal(edited.blocks[0][7],6);assert.equal(edited.blocks[0][8],'commercial');
assert.equal(edited.roadNetwork.roads[0].widthM,12);assert.equal(edited.assets.length,1);
assert.equal(JSON.stringify(source),original,'source map must never be mutated');
const other=JSON.parse(original);other.roadNetwork.roads.pop();
assert.throws(()=>A.apply(other,patch),/different|another/i,'wrong base map must be rejected');
const bad=A.empty(source);bad.assetsAdded=[{id:'evil',type:'tree',x:0,y:0,w:1,d:1,h:3,rot:0}];
assert.equal(A.apply(JSON.parse(original),bad).assets.length,0,'unsafe assets rejected');
const gone=A.empty(source);gone.buildings[id]={deleted:true};gone.roads[String(roadId)]={deleted:true};
const deleted=A.apply(JSON.parse(original),gone);
assert.equal(deleted.blocks.length,count-1);assert.equal(deleted.roadNetwork.roads.length,roadCount-1);
const html=read('world-studio-3d.html');assert.ok(html.includes('id="scene"'));assert.ok(html.includes('id="overview-canvas"'));
assert.ok(read('index.html').includes('world-overrides.js'));
console.log('PASS: shared non-destructive overrides, signature guard, safe props, edits and deletes, editor wiring.');
